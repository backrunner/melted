"""Generate native and README marks from the same original SVG geometry."""
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BRAND = ROOT / 'assets/brand'
svg = ET.parse(BRAND / 'mark.svg').getroot()
path = svg.find('{http://www.w3.org/2000/svg}path').attrib['d']
tokens = json.loads((ROOT / '.agents/design/tokens.json').read_text())
commands = re.findall(r'([MLCZ])\s*([^MLCZ]*)', path)
lines = [
    '// Generated by scripts/generate-brand-assets.py from assets/brand/mark.svg.',
    '// SPDX-FileCopyrightText: 2026 Melted contributors',
    '// SPDX-License-Identifier: GPL-3.0-or-later',
    'import SwiftUI', '',
    '/// A single flowing m, shared by the app and the project identity.',
    'public struct MeltedMark: Shape {',
    '    public init() {}',
    '    public func path(in rect: CGRect) -> Path {',
    '        let side = min(rect.width, rect.height)',
    '        func point(_ x: CGFloat, _ y: CGFloat) -> CGPoint {',
    '            CGPoint(x: rect.midX + (x / 32 - 0.5) * side,',
    '                    y: rect.midY + (y / 32 - 0.5) * side)',
    '        }',
    '        var path = Path()',
]
for command, coords in commands:
    n = [float(x) for x in coords.split()]
    p = lambda i: f'point({n[i]:g}, {n[i+1]:g})'
    if command == 'M': lines.append(f'        path.move(to: {p(0)})')
    elif command == 'L': lines.append(f'        path.addLine(to: {p(0)})')
    elif command == 'C': lines.append(f'        path.addCurve(to: {p(4)}, control1: {p(0)}, control2: {p(2)})')
    elif command == 'Z': lines.append('        path.closeSubpath()')
lines += ['        return path', '    }', '}', '']
outputs = {ROOT / 'apps/apple/Packages/MeltedKit/Sources/MeltedDesignSystem/MeltedMark.swift': '\n'.join(lines)}
for theme, colors in tokens['themes'].items():
    outputs[BRAND / f'lockup-{theme}.svg'] = f'''<svg xmlns="http://www.w3.org/2000/svg" width="268" height="96" viewBox="0 0 268 96" role="img" aria-label="Melted">
  <title>Melted</title>
  <path d="{path}" transform="translate(4 12) scale(2.25)" fill="{colors['accent']}"/>
  <text x="96" y="64" fill="{colors['text']}" font-family="-apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif" font-size="48" font-weight="650" letter-spacing="-1.5">Melted</text>
</svg>
'''
for target, content in outputs.items():
    if '--check' in sys.argv:
        if not target.exists() or target.read_text() != content:
            raise SystemExit(f'Brand asset drift: {target.relative_to(ROOT)}')
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content)
