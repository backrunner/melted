"""Generate the shared Swift palette from the approved design source."""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
tokens = json.loads((root / '.agents/design/tokens.json').read_text())
lines = ['// Generated by scripts/generate-design-tokens.py. Do not edit.', '// SPDX-FileCopyrightText: 2026 Melted contributors', '// SPDX-License-Identifier: GPL-3.0-or-later', 'import SwiftUI', '', 'public struct MeltedPalette {']
for name, value in tokens['themes']['light'].items():
    dark = tokens['themes']['dark'][name]
    lines.append(f'    public var {name}: Color {{ Color(meltedHex: dark ? "{dark[1:]}" : "{value[1:]}") }}')
lines += ['    private let dark: Bool', '    public init(_ scheme: ColorScheme) { dark = scheme == .dark }', '}', '', 'public enum MeltedLayout {']
for name, value in tokens['macLayoutPt'].items():
    lines.append(f'    public static let {name}: CGFloat = {value}')
lines += ['}', '', 'public enum MeltedType {']
for name, value in tokens['macTypographyPt'].items():
    lines.append(f'    public static let {name}: CGFloat = {value}')
lines += ['}', '', 'public enum MeltedReading {']
for name, value in tokens['readingMetricsPt'].items():
    lines.append(f'    public static let {name}: CGFloat = {value}')
for group, name in [('connectionMetricsPt', 'MeltedConnection'), ('libraryStatusMetricsPt', 'MeltedLibraryStatus')]:
    lines += ['}', '', f'public enum {name} {{']
    for name, value in tokens[group].items():
        lines.append(f'    public static let {name}: CGFloat = {value}')
lines += ['}', '', 'public enum MeltedMotion {']
for name, value in tokens['motionMs'].items():
    lines.append(f'    public static let {name}: Double = {value / 1000:g}')
lines += ['}', '', 'extension Color {', '    init(meltedHex: String) {', '        let n = UInt32(meltedHex, radix: 16)!', '        self.init(.sRGB, red: Double((n >> 16) & 255) / 255, green: Double((n >> 8) & 255) / 255, blue: Double(n & 255) / 255, opacity: 1)', '    }', '}', '']
target = root / 'apps/apple/Packages/MeltedKit/Sources/MeltedDesignSystem/Tokens.swift'
generated = '\n'.join(lines)
if '--check' in sys.argv:
    if target.read_text() != generated:
        raise SystemExit('Swift design tokens have drifted. Run scripts/generate-design-tokens.py.')
else:
    target.write_text(generated)
